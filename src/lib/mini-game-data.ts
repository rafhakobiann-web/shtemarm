export function shuffle<T>(data:readonly T[],random:()=>number=Math.random):T[]{
  const result=[...data];
  for(let i=result.length-1;i>0;i--){
    const n=random();const j=Math.max(0,Math.min(i,Math.floor((Number.isFinite(n)?n:0)*(i+1))));
    [result[i],result[j]]=[result[j]!,result[i]!];
  }
  return result;
}
/** Never repeats an ID in a round. Return actual pool size for small subjects. */
export function makeRound<T extends {id:string;subject:GameSubject}>(
  bank:readonly T[], subject:GameSubjectId, wanted:number, random:()=>number=Math.random,
):T[]{
  const pool=bank.filter(item=>subject==="mixed"||item.subject===subject);
  const result: T[]=[],seen=new Set<string>();
  for(const item of shuffle(pool,random)){
    if(seen.has(item.id))continue;
    result.push(item);seen.add(item.id);
    if(result.length===wanted)break;
  }
  return result;
}
